/* relations/tools/make-snapshot.js: writes relations/snapshot.js, the part of the curiosity database the
   standalone map (relations/index.html) needs: workspaces, curiosities (id, label, plain, workspace), suites
   (label and member ids) and proximities (label, when, then). Inside the app the map reads CuriosityDB live
   instead. Run after the database changes:  node apps/curiosities/relations/tools/make-snapshot.js
   With --check it only says whether the file is current (exit 1 when it is not). */
const fs = require("fs");
const path = require("path");
const DB = require("../../data/load-db.js");

function snapshot() {
  const d = DB.data;
  const data = {
    workspaces: d.workspaces.map((w) => ({ id: w.id, label: w.label })),
    curiosities: d.curiosities.map((c) => ({ id: c.id, label: c.label, plain: c.plain, workspace: c.workspace })),
    suites: d.suites.map((s) => ({ label: s.label, members: (s.members || []).filter((m) => m.curiosity).map((m) => ({ curiosity: m.curiosity })) })),
    proximities: d.proximities
      .filter((p) => p.when && p.then && p.when.curiosity && p.then.curiosity)
      .map((p) => ({ label: p.label, when: { curiosity: p.when.curiosity }, then: { curiosity: p.then.curiosity } })),
  };
  return "/* Generated by relations/tools/make-snapshot.js from the curiosity database. Do not edit by hand. */\nwindow.CURIO_RELATIONS_SNAPSHOT = " + JSON.stringify(data) + ";\n";
}

const out = path.join(__dirname, "..", "snapshot.js");
const text = snapshot();
if (process.argv.includes("--check")) {
  const old = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (old !== text) {
    console.log("FAIL relations/snapshot.js is out of date: run node apps/curiosities/relations/tools/make-snapshot.js");
    process.exit(1);
  }
  console.log("ok relations/snapshot.js is current");
} else {
  fs.writeFileSync(out, text);
  console.log("wrote relations/snapshot.js (" + Math.round(text.length / 1024) + " KB)");
}
