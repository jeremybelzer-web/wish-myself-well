/* Importer: turns the app's existing catalog (catalog.js, library.js, story-curiosities.js, lenses.js, model.js)
   and workspace lists (workspaces.js) into data/db-catalog.js, in the database's shape.
   Run from apps/curiosities:  node data/tools/import-catalog.js
   Re-running overwrites db-catalog.js; hand-written additions live in other data files, so nothing is lost. */

const fs = require("fs");
const path = require("path");
const APP = path.join(__dirname, "..", "..");
global.window = global;
/* Each file runs as its own global script, as the browser's script tags do (so a later const is not visible early). */
const vm = require("vm");
["catalog.js", "library.js", "story-curiosities.js", "lenses.js", "model.js"]
  .filter((f) => fs.existsSync(path.join(APP, f)))
  .forEach((f) => vm.runInThisContext(fs.readFileSync(path.join(APP, f), "utf8"), { filename: f }));
vm.runInThisContext("global.__C = CURIOSITIES; global.__S = SUITES; global.__P = PROXIMITIES;");
/* lenses.js only adds its lens suites when SUITES already exists; add them here as the app's own list would. */
(global.CURIOSITY_LENS_SUITES || []).forEach((s) => global.__S.some((x) => x.id === s.id) || global.__S.push(s));
const C = global.__C, S = global.__S, P = global.__P;

/* Workspace lists, read from workspaces.js so the database matches what the app shows. */
const wsSrc = fs.readFileSync(path.join(APP, "workspaces.js"), "utf8");
const WS = [];
wsSrc.replace(/\{ id: "([^"]+)", scope: "(scene|story)", label: "([^"]+)", note: "([^"]+)", ids: \[([^\]]*)\]/g, (_, id, scope, label, note, ids) => {
  WS.push({ id, scope, label, note, ids: (ids.match(/"([^"]+)"/g) || []).map((s) => s.slice(1, -1)) });
});

/* Lens workspaces (workspaces.js builds them from lenses.js's CURIOSITY_LENSES). */
const LENS_WS = { color: "color", wardrobeMain: "wardrobe", wardrobeBack: "wardrobe", set: "set", emotion: "emotion", emoRoad: "emo-road", comedy: "comedy", comedyMix: "comedy-mix" };
const LENSES = global.CURIOSITY_LENSES || [];
const lensOf = {};
LENSES.forEach((l) => [l.main].concat(l.subs || []).forEach((id) => (lensOf[id] = lensOf[id] || []).push(LENS_WS[l.id] || l.id)));

/* Groups whose rows no workspace lists yet. New workspaces are marked proposed. */
const GROUP_WS = {
  Camera: "camera-angle",
  "Camera move": "camera-motion",
  Motion: "character-motion",
  Light: "light",
  Place: "background",
  People: "placement",
  Sound: "music",
  Body: "movement-lines",
  Comic: "page",
  Story: "structure",
  Animation: "character-motion",
  "Shading and color": "light",
  "Dynamics, fur and Bifrost": "effects",
  "Edit and structure": "structure",
  "Scene memory": "lines",
};

/* Rows the catalog stores as a free tag get a graded scale so they can be automated. */
const TAG_SCALES = {
  angleToLine: ["matches the line", "neutral", "plays against the line"],
  angleToAction: ["matches the action", "neutral", "plays against the action"],
  eyeline: ["no one meets", "glances", "one holds the look", "both hold"],
  look: ["plain", "styled", "striking"],
  featureRate: { min: 1, max: 10, unit: "hours per main" },
  touch: ["none", "brief", "held", "constant"],
  palette: ["one color", "limited", "rich", "every color"],
  phraseScheme: ["single shots", "pairs", "threes", "fours", "long runs"],
  callResponse: ["none", "sometimes", "every cut"],
  contrastMap: { min: 0, max: 5, unit: "pairs" },
  pedal: ["nothing held", "one thing held", "several held"],
  povSwitch: ["one person throughout", "switches sometimes", "switches every scene"],
  sceneShapes: ["empty", "one big shape", "a few shapes", "busy"],
  timePerCharacter: ["one person dominates", "uneven", "even"],
};

/* Scales in a better order than the catalog's (so a sweep passes through the middle). */
const ORDER = Object.assign({
  angleHeight: ["floor", "low", "eye", "high", "overhead"],
  shotSize: ["insert", "close", "medium", "wide"],
}, global.CURIOSITY_ORDER || {});

const out = [];
const J = (x) => JSON.stringify(x);
out.push("/* Generated by data/tools/import-catalog.js from catalog.js, library.js, story-curiosities.js, model.js");
out.push("   and workspaces.js. Every existing curiosity, suite and proximity, in the database's shape.");
out.push("   Do not hand-edit: add sliders and new rows in the other data files (a row with the same id is merged). */");
out.push("(function (DB) {");

const primary = {};
const also = {};
WS.forEach((w) => w.ids.forEach((id) => (primary[id] ? (also[id] = also[id] || []).push(w.id) : (primary[id] = w.id))));

C.forEach((c) => {
  let s;
  const t = TAG_SCALES[c.id];
  if (t && Array.isArray(t)) s = ["setting", c.label, t, "Its setting in this panel."];
  else if (t) s = ["setting", c.label, [t.min, t.max, t.unit], "Its setting in this panel."];
  else if (c.options) {
    const opts = ORDER[c.id] ? ORDER[c.id].concat(c.options.filter((o) => !ORDER[c.id].includes(o))) : c.options;
    s = ["setting", c.label, opts.length >= 2 ? opts : ["off", "on"], "Its setting in this panel."];
  } else if (c.kind === "range") s = ["setting", c.label, [c.min, c.max], "Its setting in this panel."];
  else s = ["setting", c.label, ["off", "on"], "Its setting in this panel."];
  const lensWs = c.source === "lenses" ? (lensOf[c.id] || [])[0] : null;
  const ws = lensWs || primary[c.id] || GROUP_WS[c.group] || (c.group || "").replace(/^Story: .*/, "") || "structure";
  const row = { id: c.id, label: c.label, plain: c.note || c.view || c.label, workspace: ws, group: c.group, kind: "measure", sliders: [s], source: c.source || "catalog" };
  const al = [].concat(also[c.id] || [], lensOf[c.id] || []).filter((w, i, a) => w !== ws && a.indexOf(w) === i);
  if (al.length) row.also = al;
  if (c.lens) row.lens = c.lens;
  if (c.live) row.tags = ["board"];
  out.push(`DB.curiosity(${J(row)});`);
});

const wsOf = (ids) => {
  const n = {};
  ids.forEach((id) => {
    const c = C.find((x) => x.id === id);
    const w = (c && c.source === "lenses" && (lensOf[id] || [])[0]) || primary[id] || (c && GROUP_WS[c.group]);
    if (w) n[w] = (n[w] || 0) + 1;
  });
  return Object.entries(n).sort((a, b) => b[1] - a[1]).map((e) => e[0]);
};

S.forEach((s) => {
  const members = Object.entries(s.set || {}).map(([curiosity, value]) => ({ curiosity, value }));
  /* A lens suite has no fixed values: its members are the lenses looked through together. */
  (s.lenses || []).forEach((curiosity) => members.some((m) => m.curiosity === curiosity) || members.push({ curiosity }));
  const lensW = s.lenses ? s.lenses.map((id) => (lensOf[id] || [])[0]).filter(Boolean) : [];
  const w = s.kind === "emotion" ? ["emotion"] : s.kind === "genre" ? ["structure"] : lensW.length ? lensW.filter((x, i, a) => a.indexOf(x) === i) : wsOf(Object.keys(s.set || {}));
  const row = { id: s.id, label: s.label, plain: s.note, workspace: w[0] || "structure", also: w.slice(1, 3), kind: s.kind || "", members, source: "model.js" };
  out.push(`DB.suite(${J(row)});`);
});

P.forEach((p) => {
  const side = (r) => {
    const o = r.suite ? { suite: r.suite } : { curiosity: r.curiosity };
    if (r.is != null) o.is = r.is;
    if (r.change) o.change = r.change;
    return o;
  };
  const ids = [p.x.curiosity, p.y.curiosity].filter(Boolean);
  const w = ids.length ? wsOf(ids) : ["structure"];
  const row = { id: p.id, label: `When ${p.when}, ${p.then}`, plain: `When ${p.when}, ${p.then} within ${p.within} beat${p.within === 1 ? "" : "s"}.`, whenText: p.when, thenText: p.then, workspace: w[0] || "structure", also: w.slice(1), when: side(p.x), then: side(p.y), within: p.within, source: "model.js" };
  out.push(`DB.proximity(${J(row)});`);
});

/* The proximity suites automation.js defines. */
const autoSrc = fs.readFileSync(path.join(APP, "automation.js"), "utf8");
const psBlock = (autoSrc.match(/const PROXIMITY_SUITES = \[([\s\S]*?)\];/) || [])[1] || "";
let nPS = 0;
psBlock.replace(/\{ id: "([^"]+)", label: "([^"]+)", members: \[([^\]]*)\] \}/g, (_, id, label, m) => {
  const members = (m.match(/"([^"]+)"/g) || []).map((x) => x.slice(1, -1));
  const w = wsOf(members.flatMap((pid) => { const p = P.find((x) => x.id === pid); return p ? [p.x.curiosity, p.y.curiosity].filter(Boolean) : []; }));
  out.push(`DB.proximitySuite(${J({ id, label, plain: label + ": " + members.map((pid) => { const p = P.find((x) => x.id === pid); return p ? `when ${p.when}, ${p.then}` : pid; }).join("; ") + ".", workspace: w[0] || "structure", also: w.slice(1, 3), members, source: "automation.js" })});`);
  nPS++;
});

out.push('})(typeof window !== "undefined" ? window.CuriosityDB : require("./curiosity-db.js"));');
fs.writeFileSync(path.join(__dirname, "..", "db-catalog.js"), out.join("\n") + "\n");
console.log(`wrote db-catalog.js: ${C.length} curiosities, ${S.length} suites, ${P.length} proximities, ${nPS} proximity suites; workspaces read: ${WS.length}`);
